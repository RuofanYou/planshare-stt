test('middle drag pans the native timeline and stops after release',async({page})=>{
  await open(page)
  await page.setViewportSize({width:900,height:720})
  const chip=page.getByRole('button',{name:'24s0:08',exact:true}),before=await chip.boundingBox()
  if(!before)throw Error('missing reference timeline chip geometry')
  await page.mouse.move(before.x+before.width/2,before.y+before.height/2)
  await page.mouse.down({button:'middle'})
  await page.mouse.move(before.x+before.width/2-48,before.y+before.height/2,{steps:6})
  await expect.poll(async()=> (await chip.boundingBox())?.x).toBeLessThan(before.x-24)
  const stoppedX=(await chip.boundingBox())?.x
  if(stoppedX===undefined)throw Error('timeline chip disappeared after panning')
  await page.mouse.up({button:'middle'})
  await page.mouse.move(before.x+before.width/2+48,before.y+before.height/2)
  await page.waitForTimeout(50)
  await expect.poll(async()=> (await chip.boundingBox())?.x).toBe(stoppedX)
  await expect(page.getByRole('alert')).toHaveCount(0)
})
