import {test,expect,type Page} from '@playwright/test'
const source='[方案]\n名称=网页验收\n[人员]\n奶德1=小德\n[时间轴]\n-- 保留注释\n{time:00:10} {奶德1}{spell:740}准备\n'
async function open(page:Page,withText=false){
  await page.setViewportSize({width:1512,height:982})
  await page.route('**/api/editor/spells?*',r=>{
    const ids=new URL(r.request().url()).searchParams.get('ids')?.split(',').map(Number)??[]
    return r.fulfill({json:{spells:ids.map(id=>({id,name:'宁静',icon:'https://wow.zamimg.com/images/wow/icons/medium/spell_nature_tranquility.jpg',castTime:0}))}})
  })
  await page.goto('/editor')
  const text=page.getByRole('textbox',{name:'战术方案文本',exact:true})
  await expect(text).toBeVisible()
  if(withText){await text.fill(source);await text.blur();await expect(page.getByRole('button',{name:'0:10',exact:true})).toBeVisible()}
  return text
}
test('spell icons load through the same-origin metadata service',async({page})=>{
  const missing:string[]=[]
  page.on('console',message=>{if(message.text().includes('[STT editor asset missing]'))missing.push(message.text())})
  await open(page,true)
  const icon=page.locator('[data-texture^="https://wow.zamimg.com/"]').first()
  await expect(icon).toHaveAttribute('data-texture',/spell_nature_tranquility\.jpg/)
  await expect(icon).toHaveCSS('background-image',/spell_nature_tranquility\.jpg/)
  await expect(page.locator('[data-texture*="UI-CHARACTERCREATE-CLASSES"]').first()).toHaveCSS('background-image',/\/stt-editor\/classes\/[a-z]+\.png/)
  await page.getByRole('button',{name:'0:10',exact:true}).dblclick()
  await page.getByRole('button',{name:'选择技能',exact:true}).click()
  await expect.poll(()=>page.locator('[data-texture^="https://wow.zamimg.com/"]').count()).toBeGreaterThan(1)
  await expect(page.getByRole('alert')).toHaveCount(0)
  expect(missing.filter(entry=>!entry.includes('common-dropdown-c-button-arrow-down')&&!entry.includes('UI-StatusBar')&&!entry.includes('UI-Tooltip-Border'))).toEqual([])
})
